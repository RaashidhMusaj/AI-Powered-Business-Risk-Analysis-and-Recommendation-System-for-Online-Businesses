"""
Recommendation Result Data Transfer Objects.
Defines strongly-typed output models for recommendation reports and metadata.
"""

import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Dict, Any, List

from core.recommendation.constants.versions import RECOMMENDATION_VERSION

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class RecommendationMetadata:
    """
    Structured execution and summary metadata associated with a recommendation report.
    """

    highest_priority: str
    recommendation_count: int
    generated_at: str


@dataclass
class RecommendationReport:
    """
    Strongly-typed report payload generated by the recommendation pipeline.
    """

    summary: str = ""
    key_findings: List[str] = field(default_factory=list)
    priority_actions: List[str] = field(default_factory=list)
    strengths: List[str] = field(default_factory=list)
    expected_impact: str = ""
    next_review: str = ""


@dataclass(frozen=True)
class RecommendationResult:
    """
    Complete recommendation outcome containing report payload, execution metadata, and timestamps.
    """

    report: Any
    metadata: RecommendationMetadata = field(
        default_factory=lambda: RecommendationMetadata(highest_priority="", recommendation_count=0, generated_at="")
    )
    generated_timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    version: str = RECOMMENDATION_VERSION
    processing_time_ms: int = 0
